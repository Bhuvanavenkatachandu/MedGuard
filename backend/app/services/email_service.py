import os
import smtplib
from email.mime.multipart import MIMEMultipart
from email.mime.text import MIMEText
from email.mime.application import MIMEApplication
from typing import Optional
from sqlalchemy.orm import Session

from backend.app.config import settings
from backend.app.models.email_log import EmailLog
from backend.app.models.invoice import Invoice
from backend.app.database import SessionLocal

async def send_invoice_email_task(
    pharmacy_id: str,
    invoice_id: str,
    recipient_email: str,
    customer_name: str,
    invoice_number: str,
    total_amount: float,
    pdf_path: Optional[str] = None,
):
    """
    Non-blocking background worker to email the customer invoice using generic SMTP.
    If SMTP settings are not configured, the email step is safely skipped without failing the sale.
    """
    db: Session = SessionLocal()
    email_log = EmailLog(
        pharmacy_id=pharmacy_id,
        invoice_id=invoice_id,
        recipient_email=recipient_email,
        status="pending",
    )
    db.add(email_log)
    db.commit()
    db.refresh(email_log)

    smtp_host = settings.SMTP_HOST.strip()
    if not smtp_host:
        email_log.status = "skipped"
        email_log.error_message = "SMTP_HOST not configured. Email notification skipped (optional)."
        db.commit()
        db.close()
        return

    try:
        # Build multipart email message
        msg = MIMEMultipart()
        msg["From"] = settings.SMTP_FROM or "noreply@medguard.io"
        msg["To"] = recipient_email
        msg["Subject"] = f"Your Pharmacy Invoice {invoice_number} — MedGuard AI"

        html_body = f"""
        <div style="font-family: Arial, sans-serif; max-width: 600px; margin: auto; padding: 20px; border: 1px solid #e2e8f0; border-radius: 12px;">
          <h2 style="color: #1e40af; margin-top: 0;">MedGuard AI — Retail Pharmacy Invoice</h2>
          <p>Dear <strong>{customer_name}</strong>,</p>
          <p>Thank you for your purchase. Please find attached your digital invoice <strong>{invoice_number}</strong> for the amount of <strong>₹{total_amount:.2f}</strong>.</p>
          <p style="color: #64748b; font-size: 13px;">All medicines were verified under FEFO (First Expired First Out) inventory safety standards.</p>
          <hr style="border: none; border-top: 1px solid #cbd5e1; margin: 20px 0;" />
          <p style="font-size: 11px; color: #94a3b8;">This is an automated invoice generated by MedGuard AI Retail Pharmacy Suite.</p>
        </div>
        """
        msg.attach(MIMEText(html_body, "html"))

        # Attach PDF if available
        if pdf_path and os.path.exists(pdf_path):
            with open(pdf_path, "rb") as f:
                part = MIMEApplication(f.read(), Name=f"{invoice_number}.pdf")
                part["Content-Disposition"] = f'attachment; filename="{invoice_number}.pdf"'
                msg.attach(part)

        # Dispatch via SMTP
        port = settings.SMTP_PORT or 587
        if port == 465:
            with smtplib.SMTP_SSL(smtp_host, port, timeout=10.0) as server:
                if settings.SMTP_USERNAME and settings.SMTP_PASSWORD:
                    server.login(settings.SMTP_USERNAME, settings.SMTP_PASSWORD)
                server.send_message(msg)
        else:
            with smtplib.SMTP(smtp_host, port, timeout=10.0) as server:
                server.starttls()
                if settings.SMTP_USERNAME and settings.SMTP_PASSWORD:
                    server.login(settings.SMTP_USERNAME, settings.SMTP_PASSWORD)
                server.send_message(msg)

        email_log.status = "sent"
        invoice = db.query(Invoice).filter(Invoice.id == invoice_id).first()
        if invoice:
            invoice.status = "emailed"
        db.commit()

    except Exception as exc:
        email_log.status = "failed"
        email_log.error_message = f"SMTP error: {str(exc)}"
        invoice = db.query(Invoice).filter(Invoice.id == invoice_id).first()
        if invoice:
            invoice.status = "email_failed"
        db.commit()
    finally:
        db.close()
