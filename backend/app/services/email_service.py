import base64
import os
import httpx
from typing import Optional
from sqlalchemy.orm import Session

from backend.app.config import settings
from backend.app.models.email_log import EmailLog
from backend.app.models.invoice import Invoice
from backend.app.database import SessionLocal

async def send_invoice_email_task(
    pharmacy_id: str,
    invoice_id: str,
    recipient_email: str,
    customer_name: str,
    invoice_number: str,
    total_amount: float,
    pdf_path: Optional[str] = None,
):
    """
    Non-blocking background worker to email the customer invoice.
    Updates the email_logs and invoice status in the database.
    """
    db: Session = SessionLocal()
    email_log = EmailLog(
        pharmacy_id=pharmacy_id,
        invoice_id=invoice_id,
        recipient_email=recipient_email,
        status="pending",
    )
    db.add(email_log)
    db.commit()
    db.refresh(email_log)

    resend_key = settings.RESEND_API_KEY
    if not resend_key or resend_key.startswith("PASTE") or "placeholder" in resend_key:
        email_log.status = "failed"
        email_log.error_message = "RESEND_API_KEY not configured in backend environment."
        db.commit()
        db.close()
        return

    # Prepare attachments if PDF exists
    attachments = []
    if pdf_path and os.path.exists(pdf_path):
        try:
            with open(pdf_path, "rb") as f:
                content_b64 = base64.b64encode(f.read()).decode("utf-8")
                attachments.append({
                    "filename": f"{invoice_number}.pdf",
                    "content": content_b64,
                })
        except Exception as e:
            pass

    email_body = f"""
    <div style="font-family: Arial, sans-serif; max-width: 600px; margin: auto; padding: 20px; border: 1px solid #e2e8f0; border-radius: 12px;">
      <h2 style="color: #1e40af; margin-top: 0;">MedGuard AI — Retail Pharmacy Invoice</h2>
      <p>Dear <strong>{customer_name}</strong>,</p>
      <p>Thank you for your purchase. Please find attached your digital invoice <strong>{invoice_number}</strong> for the amount of <strong>₹{total_amount:.2f}</strong>.</p>
      <p style="color: #64748b; font-size: 13px;">All medicines were verified under FEFO (First Expired First Out) inventory safety standards.</p>
      <hr style="border: none; border-top: 1px solid #cbd5e1; margin: 20px 0;" />
      <p style="font-size: 11px; color: #94a3b8;">This is an automated invoice generated by MedGuard AI Retail Pharmacy Suite.</p>
    </div>
    """

    try:
        async with httpx.AsyncClient(timeout=10.0) as client:
            resp = await client.post(
                "https://api.resend.com/emails",
                headers={
                    "Authorization": f"Bearer {resend_key}",
                    "Content-Type": "application/json",
                },
                json={
                    "from": "MedGuard AI <onboarding@resend.dev>",
                    "to": [recipient_email],
                    "subject": f"Your Pharmacy Invoice {invoice_number} — MedGuard AI",
                    "html": email_body,
                    "attachments": attachments if attachments else None,
                },
            )

            if resp.status_code in (200, 201):
                res_data = resp.json()
                email_log.status = "sent"
                email_log.resend_id = res_data.get("id")
                # Update invoice status
                invoice = db.query(Invoice).filter(Invoice.id == invoice_id).first()
                if invoice:
                    invoice.status = "emailed"
                db.commit()
            else:
                email_log.status = "failed"
                email_log.error_message = f"Resend API error: {resp.status_code} {resp.text}"
                invoice = db.query(Invoice).filter(Invoice.id == invoice_id).first()
                if invoice:
                    invoice.status = "email_failed"
                db.commit()
    except Exception as exc:
        email_log.status = "failed"
        email_log.error_message = str(exc)
        invoice = db.query(Invoice).filter(Invoice.id == invoice_id).first()
        if invoice:
            invoice.status = "email_failed"
        db.commit()
    finally:
        db.close()
